CREATE TABLE IF NOT EXISTS public.shake_diagnostics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name text NOT NULL,
    phone text NOT NULL,
    vehicle text NOT NULL,
    plate_number text NOT NULL,
    service_date date NOT NULL,
    details text NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'completed', 'cancelled')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.aggregate_repairs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name text NOT NULL,
    phone text NOT NULL,
    vehicle text NOT NULL,
    plate_number text NOT NULL,
    service_date date NOT NULL,
    details text NOT NULL,
    cost numeric(12, 2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'completed', 'cancelled')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.shake_diagnostics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aggregate_repairs ENABLE ROW LEVEL SECURITY;

